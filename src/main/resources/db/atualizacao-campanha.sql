-- Para bancos criados antes da campanha e do estado ADOTADO. Executado pelo app quando a tabela CAMPANHA não existe.
ALTER TABLE CASO DROP CONSTRAINT CK_CASO_STATUS;
ALTER TABLE CASO ADD CONSTRAINT CK_CASO_STATUS CHECK (STATUS IN ('REPORTADO', 'TRIAGEM', 'ENCAMINHADO', 'ATENDIDO', 'ADOTADO', 'ARQUIVADO'));

CREATE TABLE CAMPANHA (
    ID               NUMBER(10)     NOT NULL,
    CASO_ID          NUMBER(10)     NOT NULL,
    META             NUMBER(10,2)   NOT NULL,
    VALOR_ARRECADADO NUMBER(10,2)   DEFAULT 0 NOT NULL,
    ATIVA            NUMBER(1)      DEFAULT 1 NOT NULL,
    CRIADO_EM        TIMESTAMP      NOT NULL,
    CONSTRAINT PK_CAMPANHA PRIMARY KEY (ID),
    CONSTRAINT FK_CAMPANHA_CASO FOREIGN KEY (CASO_ID) REFERENCES CASO (ID),
    CONSTRAINT CK_CAMPANHA_META CHECK (META > 0),
    CONSTRAINT CK_CAMPANHA_VALOR CHECK (VALOR_ARRECADADO >= 0),
    CONSTRAINT CK_CAMPANHA_ATIVA CHECK (ATIVA IN (0, 1))
);

CREATE INDEX IX_CAMPANHA_CASO ON CAMPANHA (CASO_ID);

CREATE SEQUENCE SEQ_CAMPANHA START WITH 1000 INCREMENT BY 1 NOCACHE;
