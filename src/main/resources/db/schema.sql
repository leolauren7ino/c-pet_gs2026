-- C-PET: DDL compativel com Oracle 12c+ e H2 em modo Oracle.
-- Ids de dominio (bairro, recurso, usuario) sao informados no seed.
-- Ids de caso, reporte e historico vem de sequences que comecam em 1000.

CREATE TABLE BAIRRO (
    ID                    NUMBER(10)    NOT NULL,
    NOME                  VARCHAR2(80)  NOT NULL,
    LAT                   NUMBER(9,6)   NOT NULL,
    LNG                   NUMBER(9,6)   NOT NULL,
    INDICE_VULNERABILIDADE NUMBER(2)    NOT NULL,
    CONSTRAINT PK_BAIRRO PRIMARY KEY (ID),
    CONSTRAINT CK_BAIRRO_INDICE CHECK (INDICE_VULNERABILIDADE BETWEEN 0 AND 20)
);

CREATE TABLE RECURSO (
    ID                NUMBER(10)    NOT NULL,
    NOME              VARCHAR2(120) NOT NULL,
    TIPO              VARCHAR2(20)  NOT NULL,
    LAT               NUMBER(9,6)   NOT NULL,
    LNG               NUMBER(9,6)   NOT NULL,
    VAGAS_DISPONIVEIS NUMBER(4)     NOT NULL,
    TIPOS_ACEITOS     VARCHAR2(120) NOT NULL,
    ATIVO             NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_RECURSO PRIMARY KEY (ID),
    CONSTRAINT CK_RECURSO_TIPO CHECK (TIPO IN ('ONG', 'CLINICA', 'UNIDADE_MOVEL', 'ORGAO_PUBLICO')),
    CONSTRAINT CK_RECURSO_VAGAS CHECK (VAGAS_DISPONIVEIS >= 0)
);

CREATE TABLE USUARIO (
    ID         NUMBER(10)   NOT NULL,
    NOME       VARCHAR2(80) NOT NULL,
    PERFIL     VARCHAR2(10) NOT NULL,
    RECURSO_ID NUMBER(10),
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('OPERADOR', 'AGENTE')),
    CONSTRAINT FK_USUARIO_RECURSO FOREIGN KEY (RECURSO_ID) REFERENCES RECURSO (ID)
);

CREATE TABLE CASO (
    ID                    NUMBER(10)   NOT NULL,
    TIPO                  VARCHAR2(20) NOT NULL,
    QTD_ANIMAIS           NUMBER(4)    NOT NULL,
    LAT                   NUMBER(9,6)  NOT NULL,
    LNG                   NUMBER(9,6)  NOT NULL,
    CELULA                VARCHAR2(20) NOT NULL,
    BAIRRO_ID             NUMBER(10)   NOT NULL,
    STATUS                VARCHAR2(12) NOT NULL,
    SCORE                 NUMBER(3)    DEFAULT 0 NOT NULL,
    RECURSO_ID            NUMBER(10),
    CODIGO_ACOMPANHAMENTO VARCHAR2(12) NOT NULL,
    CRIADO_EM             TIMESTAMP    NOT NULL,
    ATUALIZADO_EM         TIMESTAMP    NOT NULL,
    SIMULADO              NUMBER(1)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CASO PRIMARY KEY (ID),
    CONSTRAINT UK_CASO_CODIGO UNIQUE (CODIGO_ACOMPANHAMENTO),
    CONSTRAINT CK_CASO_TIPO CHECK (TIPO IN ('FERIDO', 'DOENTE', 'FILHOTE', 'COLONIA', 'MAUS_TRATOS', 'RISCO_SANITARIO')),
    CONSTRAINT CK_CASO_STATUS CHECK (STATUS IN ('REPORTADO', 'TRIAGEM', 'ENCAMINHADO', 'ATENDIDO', 'ARQUIVADO')),
    CONSTRAINT CK_CASO_QTD CHECK (QTD_ANIMAIS >= 1),
    CONSTRAINT FK_CASO_BAIRRO FOREIGN KEY (BAIRRO_ID) REFERENCES BAIRRO (ID),
    CONSTRAINT FK_CASO_RECURSO FOREIGN KEY (RECURSO_ID) REFERENCES RECURSO (ID)
);

CREATE INDEX IX_CASO_STATUS ON CASO (STATUS);
CREATE INDEX IX_CASO_CELULA ON CASO (CELULA);

CREATE TABLE REPORTE (
    ID               NUMBER(10)     NOT NULL,
    CASO_ID          NUMBER(10)     NOT NULL,
    DESCRICAO        VARCHAR2(1000),
    FOTO_PATH        VARCHAR2(120),
    CONTATO_OPCIONAL VARCHAR2(120),
    CRIADO_EM        TIMESTAMP      NOT NULL,
    CONSTRAINT PK_REPORTE PRIMARY KEY (ID),
    CONSTRAINT FK_REPORTE_CASO FOREIGN KEY (CASO_ID) REFERENCES CASO (ID)
);

CREATE INDEX IX_REPORTE_CASO ON REPORTE (CASO_ID);

CREATE TABLE HISTORICO_STATUS (
    ID              NUMBER(10)     NOT NULL,
    CASO_ID         NUMBER(10)     NOT NULL,
    STATUS_ANTERIOR VARCHAR2(12),
    STATUS_NOVO     VARCHAR2(12)   NOT NULL,
    AUTOR           VARCHAR2(80)   NOT NULL,
    OBSERVACAO      VARCHAR2(500),
    CRIADO_EM       TIMESTAMP      NOT NULL,
    CONSTRAINT PK_HISTORICO PRIMARY KEY (ID),
    CONSTRAINT FK_HISTORICO_CASO FOREIGN KEY (CASO_ID) REFERENCES CASO (ID)
);

CREATE INDEX IX_HISTORICO_CASO ON HISTORICO_STATUS (CASO_ID);

CREATE SEQUENCE SEQ_CASO START WITH 1000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_REPORTE START WITH 1000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_HISTORICO START WITH 1000 INCREMENT BY 1 NOCACHE;
